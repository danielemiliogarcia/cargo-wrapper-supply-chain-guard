//! Regenerates the immutable cargo-vet evidence bundled with Supply Chain Guard.
//! It downloads pinned TOML as bounded data and never downloads or executes crate source.

use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::thread;
use std::time::Duration;

const MAX_SOURCE_BYTES: u64 = 8 * 1024 * 1024;
const DOWNLOAD_ATTEMPTS: usize = 4;

type BoxError = Box<dyn std::error::Error + Send + Sync>;
type Result<T> = std::result::Result<T, BoxError>;

#[derive(Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
struct SourceManifest {
    baseline: String,
    sources: Vec<Source>,
}

#[derive(Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
struct Source {
    id: String,
    display_name: String,
    repository: String,
    commit: String,
    url: String,
    sha256: String,
}

#[derive(serde::Serialize)]
#[serde(rename_all = "kebab-case")]
struct Provenance<'a> {
    baseline: &'a str,
    sources: Vec<ProvenanceSource<'a>>,
}

#[derive(serde::Serialize)]
#[serde(rename_all = "kebab-case")]
struct ProvenanceSource<'a> {
    id: &'a str,
    display_name: &'a str,
    repository: &'a str,
    commit: &'a str,
    sha256: &'a str,
    retained_audits: usize,
    retained_violations: usize,
    removed_wildcard_audits: usize,
    removed_trusted_publishers: usize,
    removed_unrelated_audits: usize,
}

#[derive(serde::Serialize)]
#[serde(rename_all = "kebab-case")]
struct EdgeProvenance {
    baseline: String,
    edges: Vec<ProvenanceEdge>,
}

#[derive(serde::Serialize)]
#[serde(rename_all = "kebab-case")]
struct ProvenanceEdge {
    crate_name: String,
    entry_sha256: String,
    producers: Vec<String>,
}

#[derive(Default)]
struct Counts {
    audits: usize,
    violations: usize,
    wildcard: usize,
    trusted: usize,
    unrelated: usize,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("generate-curated-audits: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let check = match std::env::args().nth(1).as_deref() {
        Some("--update") => false,
        Some("--check") => true,
        _ => return Err("use --check, or explicitly authorize replacement with --update".into()),
    };
    let helper = PathBuf::from(
        std::env::var_os("SUPPLY_CHAIN_GUARD_CARGO_VET")
            .ok_or("SUPPLY_CHAIN_GUARD_CARGO_VET must name the pinned helper")?,
    );
    verify_helper(&helper)?;
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let manifest_path = root.join("curation/sources.toml");
    let manifest: SourceManifest = toml::from_str(&fs::read_to_string(&manifest_path)?)?;
    validate_manifest(&manifest)?;

    let output = root.join("curation/generated");
    fs::create_dir_all(&output)?;
    let mut combined = toml::map::Map::new();
    combined.insert("audits".into(), toml::Value::Table(toml::map::Map::new()));
    let mut provenance = Vec::new();
    let mut edge_producers = BTreeMap::<(String, String), BTreeSet<String>>::new();

    for source in &manifest.sources {
        let bytes = download(source)?;
        let parsed: toml::Value = toml::from_str(std::str::from_utf8(&bytes)?)?;
        let (filtered, counts) = filter(parsed)?;
        index_audit_edges(&filtered, &source.id, &mut edge_producers)?;
        merge_audits(&mut combined, &filtered)?;
        write_or_check(
            &output.join(format!("{}.toml", source.id)),
            canonical_audits(&helper, &filtered)?.as_bytes(),
            check,
        )?;
        provenance.push(ProvenanceSource {
            id: &source.id,
            display_name: &source.display_name,
            repository: &source.repository,
            commit: &source.commit,
            sha256: &source.sha256,
            retained_audits: counts.audits,
            retained_violations: counts.violations,
            removed_wildcard_audits: counts.wildcard,
            removed_trusted_publishers: counts.trusted,
            removed_unrelated_audits: counts.unrelated,
        });
    }

    let combined = toml::Value::Table(combined);
    write_or_check(
        &output.join("combined.toml"),
        canonical_audits(&helper, &combined)?.as_bytes(),
        check,
    )?;
    let provenance = toml::to_string_pretty(&Provenance {
        baseline: &manifest.baseline,
        sources: provenance,
    })?;
    write_or_check(
        &output.join("provenance.toml"),
        format!("# Generated by generate_curated_audits.rs; do not edit.\n{provenance}").as_bytes(),
        check,
    )?;
    let edge_provenance = EdgeProvenance {
        baseline: manifest.baseline.clone(),
        edges: edge_producers
            .into_iter()
            .map(|((crate_name, entry_sha256), producers)| ProvenanceEdge {
                crate_name,
                entry_sha256,
                producers: producers.into_iter().collect(),
            })
            .collect(),
    };
    write_or_check(
        &output.join("edge-provenance.toml"),
        format!(
            "# Generated exact audit-edge provenance; do not edit.\n{}",
            toml::to_string_pretty(&edge_provenance)?
        )
        .as_bytes(),
        check,
    )?;
    println!(
        "{} {} from {} pinned producers",
        if check { "verified" } else { "generated" },
        manifest.baseline,
        manifest.sources.len()
    );
    Ok(())
}

fn index_audit_edges(
    filtered: &toml::Value,
    producer: &str,
    output: &mut BTreeMap<(String, String), BTreeSet<String>>,
) -> Result<()> {
    let audits = filtered
        .get("audits")
        .and_then(toml::Value::as_table)
        .ok_or("filtered evidence has no audits table")?;
    for (crate_name, entries) in audits {
        for entry in entries
            .as_array()
            .ok_or_else(|| format!("audits.{crate_name} must be an array"))?
        {
            let canonical = toml::to_string(entry)?;
            let digest = format!("{:x}", Sha256::digest(canonical.as_bytes()));
            output
                .entry((crate_name.clone(), digest))
                .or_default()
                .insert(producer.to_owned());
        }
    }
    Ok(())
}

fn validate_manifest(manifest: &SourceManifest) -> Result<()> {
    if manifest.baseline.trim().is_empty() || manifest.sources.is_empty() {
        return Err("baseline identity and at least one source are required".into());
    }
    let mut ids = BTreeSet::new();
    for source in &manifest.sources {
        if !ids.insert(source.id.as_str()) {
            return Err(format!("duplicate source id {}", source.id).into());
        }
        if source.commit.len() != 40
            || !source.commit.bytes().all(|byte| byte.is_ascii_hexdigit())
            || source.sha256.len() != 64
            || !source.sha256.bytes().all(|byte| byte.is_ascii_hexdigit())
            || !source.url.contains(&source.commit)
            || !source.url.starts_with("https://")
        {
            return Err(format!("source {} is not immutably pinned", source.id).into());
        }
    }
    Ok(())
}

fn download(source: &Source) -> Result<Vec<u8>> {
    let mut attempt = 1;
    let response = loop {
        match ureq::get(&source.url).call() {
            Ok(response) => break response,
            Err(error) if attempt < DOWNLOAD_ATTEMPTS && retryable_download_error(&error) => {
                eprintln!(
                    "{}: transient download failure ({error}); retrying ({attempt}/{DOWNLOAD_ATTEMPTS})",
                    source.id
                );
                thread::sleep(Duration::from_millis(500 * attempt as u64));
                attempt += 1;
            }
            Err(error) => return Err(error.into()),
        }
    };
    if let Some(length) = response.header("content-length")
        && length.parse::<u64>()? > MAX_SOURCE_BYTES
    {
        return Err(format!("{} exceeds the source size limit", source.id).into());
    }
    let mut bytes = Vec::new();
    response
        .into_reader()
        .take(MAX_SOURCE_BYTES + 1)
        .read_to_end(&mut bytes)?;
    if bytes.len() as u64 > MAX_SOURCE_BYTES {
        return Err(format!("{} exceeds the source size limit", source.id).into());
    }
    let actual = format!("{:x}", Sha256::digest(&bytes));
    if actual != source.sha256 {
        return Err(format!(
            "{} digest mismatch: expected {}, got {actual}",
            source.id, source.sha256
        )
        .into());
    }
    Ok(bytes)
}

fn retryable_download_error(error: &ureq::Error) -> bool {
    match error {
        ureq::Error::Status(code, _) => *code == 429 || *code >= 500,
        ureq::Error::Transport(_) => true,
    }
}

fn filter(mut input: toml::Value) -> Result<(toml::Value, Counts)> {
    let table = input
        .as_table_mut()
        .ok_or("cargo-vet audits input must be a TOML table")?;
    let criteria = table
        .get("criteria")
        .and_then(toml::Value::as_table)
        .cloned()
        .unwrap_or_default();
    let mut counts = Counts {
        wildcard: count_entries(table.remove("wildcard-audits")),
        trusted: count_entries(table.remove("trusted")),
        ..Counts::default()
    };

    let audits = table
        .remove("audits")
        .and_then(|value| value.as_table().cloned())
        .unwrap_or_default();
    let mut filtered_audits = toml::map::Map::new();
    for (crate_name, entries) in audits {
        let entries = entries
            .as_array()
            .ok_or_else(|| format!("audits.{crate_name} must be an array"))?;
        let mut filtered = Vec::new();
        for entry in entries {
            let mut entry = entry.clone();
            let entry_table = entry
                .as_table_mut()
                .ok_or_else(|| format!("audits.{crate_name} entry must be a table"))?;
            let mapped = mapped_criteria(entry_table.get("criteria"), &criteria)?;
            if mapped.is_empty() {
                counts.unrelated += 1;
                continue;
            }
            entry_table.insert(
                "criteria".into(),
                if mapped.len() == 1 {
                    toml::Value::String(mapped[0].clone())
                } else {
                    toml::Value::Array(mapped.into_iter().map(toml::Value::String).collect())
                },
            );
            if entry_table.contains_key("violation") {
                counts.violations += 1;
            } else {
                counts.audits += 1;
            }
            filtered.push(entry);
        }
        if !filtered.is_empty() {
            filtered_audits.insert(crate_name, toml::Value::Array(filtered));
        }
    }
    let mut output = toml::map::Map::new();
    output.insert("audits".into(), toml::Value::Table(filtered_audits));
    Ok((toml::Value::Table(output), counts))
}

fn mapped_criteria(
    value: Option<&toml::Value>,
    definitions: &toml::map::Map<String, toml::Value>,
) -> Result<Vec<String>> {
    let names = string_or_array(value.ok_or("audit entry is missing criteria")?)?;
    let mut mapped = BTreeSet::new();
    for name in names {
        let closure = criterion_closure(&name, definitions, &mut BTreeSet::new())?;
        if closure.contains("safe-to-deploy") {
            mapped.insert("safe-to-deploy".to_owned());
        } else if closure.contains("safe-to-run") {
            mapped.insert("safe-to-run".to_owned());
        }
    }
    Ok(mapped.into_iter().collect())
}

fn criterion_closure(
    name: &str,
    definitions: &toml::map::Map<String, toml::Value>,
    visiting: &mut BTreeSet<String>,
) -> Result<BTreeSet<String>> {
    if !visiting.insert(name.to_owned()) {
        return Err(format!("criteria implication cycle involving {name}").into());
    }
    let mut result = BTreeSet::from([name.to_owned()]);
    if name == "safe-to-deploy" {
        result.insert("safe-to-run".to_owned());
    }
    if let Some(entry) = definitions.get(name) {
        let table = entry
            .as_table()
            .ok_or_else(|| format!("criteria.{name} must be a table"))?;
        if let Some(implies) = table.get("implies") {
            for implied in string_or_array(implies)? {
                result.extend(criterion_closure(&implied, definitions, visiting)?);
            }
        }
    }
    visiting.remove(name);
    Ok(result)
}

fn string_or_array(value: &toml::Value) -> Result<Vec<String>> {
    if let Some(value) = value.as_str() {
        return Ok(vec![value.to_owned()]);
    }
    value
        .as_array()
        .ok_or_else(|| -> BoxError { "expected a string or string array".into() })?
        .iter()
        .map(|value| {
            value
                .as_str()
                .map(ToOwned::to_owned)
                .ok_or_else(|| "criteria arrays must contain strings".into())
        })
        .collect()
}

fn count_entries(value: Option<toml::Value>) -> usize {
    value
        .and_then(|value| value.as_table().cloned())
        .map(|table| {
            table
                .values()
                .map(|value| value.as_array().map_or(0, Vec::len))
                .sum()
        })
        .unwrap_or(0)
}

fn merge_audits(
    combined: &mut toml::map::Map<String, toml::Value>,
    source: &toml::Value,
) -> Result<()> {
    let target = combined
        .get_mut("audits")
        .and_then(toml::Value::as_table_mut)
        .ok_or("combined audits table is missing")?;
    let audits = source
        .get("audits")
        .and_then(toml::Value::as_table)
        .ok_or("source audits table is missing")?;
    for (name, entries) in audits {
        let destination = target
            .entry(name.clone())
            .or_insert_with(|| toml::Value::Array(Vec::new()))
            .as_array_mut()
            .ok_or("combined crate audit entry is not an array")?;
        destination.extend(
            entries
                .as_array()
                .ok_or("source crate audit entry is not an array")?
                .clone(),
        );
    }
    Ok(())
}

fn verify_helper(helper: &Path) -> Result<()> {
    if !helper.is_absolute() || !helper.is_file() {
        return Err("pinned cargo-vet helper must be an absolute regular file".into());
    }
    let output = Command::new(helper).arg("--version").output()?;
    if !output.status.success() || String::from_utf8(output.stdout)?.trim() != "cargo-vet 0.10.2" {
        return Err("curation requires cargo-vet 0.10.2".into());
    }
    Ok(())
}

fn canonical_audits(helper: &Path, value: &toml::Value) -> Result<String> {
    let temporary = tempfile::tempdir()?;
    fs::write(
        temporary.path().join("audits.toml"),
        toml::to_string_pretty(value)?,
    )?;
    fs::write(
        temporary.path().join("config.toml"),
        "[cargo-vet]\nversion = \"0.10\"\n",
    )?;
    fs::write(temporary.path().join("imports.lock"), "")?;
    let output = Command::new(helper)
        .arg("vet")
        .arg("fmt")
        .arg("--store-path")
        .arg(temporary.path())
        .output()?;
    if !output.status.success() {
        return Err(format!(
            "cargo-vet rejected generated evidence: {}",
            String::from_utf8_lossy(&output.stderr)
        )
        .into());
    }
    Ok(format!(
        "# Generated by generate_curated_audits.rs; do not edit.\n{}",
        fs::read_to_string(temporary.path().join("audits.toml"))?
    ))
}

fn write_or_check(path: &Path, bytes: &[u8], check: bool) -> Result<()> {
    if check {
        let actual = fs::read(path)?;
        if actual != bytes {
            return Err(format!("generated output differs from {}", path.display()).into());
        }
        return Ok(());
    }
    let temporary = path.with_extension("tmp");
    fs::write(&temporary, bytes)?;
    fs::rename(temporary, path)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filtering_keeps_only_audit_path_and_violation_evidence() {
        let input: toml::Value = toml::from_str(
            "[criteria.reviewed]\ndescription='reviewed'\nimplies='safe-to-run'\n[criteria.license]\ndescription='license'\n[[audits.demo]]\nwho='fixture'\ncriteria='reviewed'\nversion='1.0.0'\n[[audits.demo]]\nwho='fixture'\ncriteria='license'\nversion='2.0.0'\n[[audits.demo]]\nwho='fixture'\ncriteria='reviewed'\nviolation='>=3.0.0'\n[[wildcard-audits.demo]]\ncriteria='safe-to-run'\nuser-id=1\nstart='2020-01-01'\nend='2030-01-01'\n[[trusted.demo]]\ncriteria='safe-to-run'\nuser-id=1\nstart='2020-01-01'\nend='2030-01-01'\n",
        )
        .unwrap();
        let (filtered, counts) = filter(input).unwrap();
        let text = toml::to_string(&filtered).unwrap();
        assert!(!text.contains("wildcard-audits"));
        assert!(!text.contains("trusted"));
        assert!(!text.contains("license"));
        assert!(text.contains("safe-to-run"));
        assert!(text.contains("violation"));
        assert_eq!(counts.audits, 1);
        assert_eq!(counts.violations, 1);
        assert_eq!(counts.unrelated, 1);
        assert_eq!(counts.wildcard, 1);
        assert_eq!(counts.trusted, 1);
    }
}
